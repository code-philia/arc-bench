/** Dry-run REQs with mock UI/helpers to check data ownership, not app behavior.
 * Usage: node curation_tool/check_bookstack_preparation.mjs [typescript-module]
 */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tests = join(root, 'arc-bench/bookstack/tests');
const require = createRequire(import.meta.url);
const ts = require(process.argv[2] ?? 'typescript');
const data = await import(pathToFileURL(join(tests, 'fixtures/data.ts')).href);
const specs = readdirSync(tests).filter(name => name.endsWith('.spec.ts')).sort();
const registered = [];
const owned = new WeakMap();
const names = new Set();
const generations = [];
let active;

const wrappedData = { ...data };
for (const [key, generate] of Object.entries(data)) {
  if (!/^generate\w+Data$/.test(key)) continue;
  wrappedData[key] = (...args) => {
    assert.ok(active, `Material generated outside a test: ${key}`);
    const result = generate(...args);
    owned.set(result, active.id);
    for (const value of Object.values(result)) active.values.add(value);
    const name = result.name ?? result.title ?? result.nickname;
    assert.ok(!names.has(name), `Repeated material identity: ${name}`);
    names.add(name);
    generations.push({ test: active.title, repetition: active.repetition, generator: key });
    return result;
  };
}

function assertOwned(value) {
  assert.equal(owned.get(value), active.id, 'Material belongs to another test or is not generated');
}
function locator() {
  const result = {
    click: async () => {}, fill: async value => assert.ok(active.values.has(value), 'UI input not generated by this test'),
    filter: () => result, or: () => result,
    getByRole: () => result, getByLabel: () => result,
    getByPlaceholder: () => result, getByText: () => result,
  };
  return result;
}
const page = { ...locator(), reload: async () => {} };
const matcher = new Proxy({}, { get: (_, key) => key === 'not' ? matcher : async () => {} });
const expect = () => matcher;
function component() {
  return {
    activate: async () => {}, open: async () => {},
    expectVisible: async () => {}, expectCount: async () => {}, expectAbsent: async () => {}, expectMaxItems: async () => {},
    fill: async value => assert.ok(active.values.has(value), 'UI input not generated by this test'),
    expectValue: async value => assert.ok(active.values.has(value), 'Expected field value not owned by this test'),
    set: async () => {}, expectState: async () => {}, item: () => component(),
  };
}
const helpers = {
  ACCOUNT: data.ACCOUNT,
  action: component, collection: component, textField: component, navigationAction: component,
  pageEditor: () => ({ title: component(), body: component() }),
  objectNavigation: (_, name) => {
    assert.ok(active.values.has(name), 'Navigation identity not owned by this test');
    return component();
  },
  toggle: component, favorite: component, content: component,
  accountIdentity: component,
  detailContent: (_, owner, value) => {
    assert.ok(active.values.has(owner) && active.values.has(value), 'Detail assertion is not owned by this test');
    return component();
  },
  withFavoriteCleanup: async (_, body) => body(book => assert.ok(active.books.has(book), 'Cannot restore another test\'s favorites')),
  enter: async () => {}, home: async () => {}, go: async () => {}, login: async () => {},
  beginShelf: async () => {}, beginBook: async () => {},
  region: locator, button: locator, entry: locator, field: locator,
  navigationEntry: async () => locator(),
  expectToggleState: async () => {}, expectFavoriteState: async () => {},
  expectFieldValue: async (_, name, value) => assert.ok(active.values.has(value), 'Expected field value not owned by this test'),
  heading: async (_, value) => assert.ok(['Shelves', 'Books'].includes(value) || active.values.has(value)),
  text: async (_, value, owner) => assert.ok(active.values.has(value) && active.values.has(owner), 'Expected content/owner not owned by this test'),
  metadata: async (_, ...values) => values.forEach(value => assert.ok(active.values.has(value))),
  expectMetadata: async (_, ...values) => values.forEach(value => assert.ok(active.values.has(value), 'Metadata expectation not owned by this test')),
  createShelf: async (_, material) => {
    assertOwned(material); active.shelves.add(material.name); return material.name;
  },
  createBook: async (_, material) => {
    assertOwned(material); active.books.add(material.name); return material.name;
  },
  createShelfBook: async (_, material) => {
    assertOwned(material);
    assert.ok(active.shelves.has(material.shelfName), 'Parent shelf not created by this test');
    active.books.add(material.name); return material.name;
  },
  openShelf: async (_, name) => assert.ok(active.shelves.has(name)),
  openBook: async (_, name) => assert.ok(active.books.has(name)),
  createPage: async (_, material, draft = false) => {
    assert.equal(material.chapterName, undefined, 'Unsupported chapter page preparation must be rejected');
    assertOwned(material);
    assert.ok(active.books.has(material.bookName), 'Parent book not created by this test');
    const event = generations.findLast(event => event.test === active.title && event.repetition === active.repetition);
    assert.equal(event.generator === 'generateDraftData', draft);
    return material.title;
  },
};

for (const filename of specs) {
  const source = readFileSync(join(tests, filename), 'utf8');
  const compiled = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
    reportDiagnostics: true,
  });
  assert.equal(compiled.diagnostics?.length ?? 0, 0, filename);
  const mod = { exports: {} };
  const localRequire = specifier => {
    if (specifier === './fixtures/data') return wrappedData;
    if (specifier === './helpers') return helpers;
    if (specifier === '@playwright/test') return {
      expect, test: Object.assign((title, body) => registered.push({ filename, title, body }), { setTimeout: () => {} }),
    };
    throw new Error(`Unexpected test dependency: ${specifier}`);
  };
  new Function('require', 'module', 'exports', compiled.outputText)(localRequire, mod, mod.exports);
}
assert.equal(registered.length, 35);
for (let repetition = 1; repetition <= 2; repetition++) {
  for (const test of registered) {
    active = {
      id: `${repetition}:${test.title}`, title: test.title, repetition,
      values: new Set(), shelves: new Set(), books: new Set(),
    };
    await test.body({ page });
    active = undefined;
  }
}
const requirement = readFileSync(join(tests, '../requirements/requirements.yaml'), 'utf8');
const helperSource = readFileSync(join(tests, 'helpers.ts'), 'utf8');
const files = [...specs.map(name => join(tests, name)), join(tests, 'helpers.ts'), join(tests, 'fixtures/data.ts'), join(tests, '../requirements/requirements.yaml')];
const report = {
  schema_version: 1,
  method: 'REQ callback dry-run with mock UI and helper ownership checks; not Playwright or app execution',
  spec_files: specs.length, tests: registered.length, repetitions: 2, generated_materials: generations.length,
  checks: {
    no_generation_at_module_scope: true, per_test_material_ownership: true,
    parent_shelves_and_books_created_in_same_test: true,
    distinct_identities_across_tests_and_repetitions: true,
    generated_values_used_for_inputs_and_expected_content: true,
    no_bootstrap_constant: !helperSource.includes('BOOTSTRAP_SHELF'),
    no_seed_headers: !requirement.includes('Seed prerequisites'),
  },
  open_findings: [],
  resolved_findings: [{ id: 'PREP-01', detail: 'createPage explicitly rejects chapterName before UI operations; chapter-page creation is not silently redirected to the book.' }],
  deferred: ['Shared account history and arbitrary ranking isolation remain bounded; see quality_governance.'],
  limits: ['Mock helpers do not prove UI behavior, permissions, persistence, actual dataset readiness or list membership.', 'This check does not access a live generated web system.'],
  generations,
  source_sha256: Object.fromEntries(files.map(file => [file.slice(root.length + 1).replaceAll('\\', '/'), createHash('sha256').update(readFileSync(file)).digest('hex')])),
};
const reportDirectory = resolve(root, 'ref/bookstack');
mkdirSync(reportDirectory, { recursive: true });
writeFileSync(resolve(reportDirectory, 'data_preparation_audit.json'), JSON.stringify(report, null, 2) + '\n', 'utf8');
console.log(JSON.stringify({ tests: registered.length, repetitions: 2, generated_materials: generations.length, checks: report.checks, latent_findings: report.open_findings.length }));
